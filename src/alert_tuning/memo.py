"""Tuning documentation: the memo a model-governance function or an inspector asks for."""
from __future__ import annotations

import datetime as dt
import math

from .data import Dataset
from .rules import RULES


def _pct(x: float) -> str:
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.0%}"


def _frac(m: dict) -> str:
    return f"{m['detected']}/{m['scenarios']}" if m["scenarios"] else "-"


def _fmt(v) -> str:
    return f"{v:,}" if isinstance(v, int) and abs(v) >= 10_000 else (f"{v:g}" if isinstance(v, float) else str(v))


def build_memo(ds: Dataset, results: dict, btl: dict | None = None, today: dt.date | None = None) -> str:
    today = today or dt.date.today()
    p = results["portfolio"]
    base, rec = p["baseline"]["all"], p["recommended"]["all"]
    hb, hr = p["baseline"]["holdout"], p["recommended"]["holdout"]
    minutes = results["minutes_per_alert"]
    cut = 1 - rec["false_alerts"] / base["false_alerts"] if base["false_alerts"] else 0.0
    out = [
        "# Transaction-monitoring tuning memo",
        "",
        f"*Generated by alert-tuning-lab on {today.isoformat()}. Data: `{ds.directory}` "
        f"({len(ds.customers):,} customers, {len(ds.txns):,} transactions, {ds.start} to {ds.end}).*",
        "",
        "> **Synthetic data.** The figures below demonstrate the method on planted scenarios. They are not detection rates for any real institution. "
        "Re-run the lab on your own labelled alerts before changing production thresholds.",
        "",
        "## 1. Purpose and scope",
        "Review of nine monitoring rules, selection of thresholds with documented evidence, and an estimate of what the new thresholds could miss.",
        "",
        "## 2. Method",
        f"- **Ground truth:** planted suspicious scenarios, and benign *look-alike* scenarios that resemble them, from the dataset's `scenarios.csv`.",
        "- **Split:** scenarios are assigned by a stable hash to *tuning* (about 60%) or *holdout* (about 40%). Thresholds are chosen on the tuning part only; the holdout part is the out-of-sample check.",
        f"- **Objective:** for each rule, the fewest false alerts on the tuning scenarios that still detect at least {_pct(results['target_recall'])} of that rule's own typology "
        "(or the best achievable recall if the target is out of reach).",
        "- **Definitions:** a *true* alert falls on a suspicious scenario of the rule's typology (customer and dates match, 7-day margin); an *incidental* alert falls on a suspicious scenario of another typology; "
        "a *false* alert falls on a look-alike or on ordinary activity. Alerts are suppressed to one per customer per 7 days.",
        f"- **Workload:** {minutes:g} minutes of analyst time per alert (assumption).",
        "",
        "## 3. Portfolio result",
        "",
        "| | Current thresholds | Recommended |",
        "|---|---:|---:|",
        f"| Alerts (all data) | {base['alerts']:,} | {rec['alerts']:,} |",
        f"| False alerts | {base['false_alerts']:,} | {rec['false_alerts']:,} |",
        f"| Alert productivity (true + incidental) | {_pct(base['precision'])} | {_pct(rec['precision'])} |",
        f"| Suspicious scenarios detected by any rule | {base['detected_any']}/{base['scenarios']} | {rec['detected_any']}/{rec['scenarios']} |",
        f"| Holdout: scenarios detected by any rule | {hb['detected_any']}/{hb['scenarios']} | {hr['detected_any']}/{hr['scenarios']} |",
        f"| Alerts per 1,000 customers per month | {base['alerts_per_1000_customers_month']:.1f} | {rec['alerts_per_1000_customers_month']:.1f} |",
        f"| Analyst hours over the period | {base['analyst_hours']:.0f} | {rec['analyst_hours']:.0f} |",
        "",
        f"False alerts fall by **{_pct(cut)}**. ",
        "",
        "## 4. Rule by rule",
        "",
        "| Rule | Typology | Alerts now -> new | False alerts now -> new | Detected, tuning (now / new) | Detected, holdout (now / new) |",
        "|---|---|---:|---:|---:|---:|",
    ]
    warnings = []
    for rule, block in results["rules"].items():
        b, r = block["baseline"], block["recommended"]
        out.append(f"| {rule} | {RULES[rule].typology} | {b['all']['alerts']} -> {r['all']['alerts']} | {b['all']['false_alerts']} -> {r['all']['false_alerts']} | "
                   f"{_frac(b['tune'])} / {_frac(r['tune'])} | {_frac(b['holdout'])} / {_frac(r['holdout'])} |")
        if r["holdout"]["scenarios"] and r["holdout"]["detected"] < b["holdout"]["detected"]:
            warnings.append(f"`{rule}`: holdout detection falls from {_frac(b['holdout'])} to {_frac(r['holdout'])}; review before adopting.")
        if r["holdout"]["scenarios"] and r["holdout"]["scenarios"] < 5:
            warnings.append(f"`{rule}`: only {r['holdout']['scenarios']} holdout scenario(s); the holdout result is weak evidence.")
    out += ["", "### Detection by typology (any rule, holdout)", "", "| Typology | Current | Recommended |", "|---|---:|---:|"]
    for typ, (d, n) in p["baseline"]["per_typology"]["holdout"].items():
        d2, n2 = p["recommended"]["per_typology"]["holdout"][typ]
        out.append(f"| {typ} | {d}/{n} | {d2}/{n2} |")
    out += ["", "## 5. Parameter change log", "", "| Rule | Parameter | From | To | Meaning |", "|---|---|---:|---:|---|"]
    changed = 0
    for rule, block in results["rules"].items():
        for name, new in block["recommended"]["params"].items():
            old = block["baseline"]["params"][name]
            if new != old:
                changed += 1
                out.append(f"| {rule} | `{name}` | {_fmt(old)} | {_fmt(new)} | {RULES[rule].params[name].doc} |")
    if not changed:
        out.append("| - | no change recommended | | | |")
    out += ["", "Each change is the combination with the fewest false alerts on tuning scenarios that keeps the target detection; "
            "see `sweeps.csv` for every combination tried and the charts in `charts/`."]
    if btl:
        e = btl["evaluation"]
        near, other = e["strata"]["near_miss"], e["strata"]["other"]
        out += ["", "## 6. Below-the-line test of the recommended thresholds", "",
                f"A sample of {near['n'] + other['n']} customer-months that raised **no alert** under the recommended thresholds was drawn: "
                f"{near['n']} *near-misses* (a loosened version of a rule would have alerted) and {other['n']} others.", "",
                "| Stratum | Population | Sampled | Suspicious found | Rate (95% CI) |", "|---|---:|---:|---:|---:|"]
        for name, s in (("near-miss", near), ("other", other)):
            pop = btl["population"]["near_miss" if name == "near-miss" else "other"]
            out.append(f"| {name} | {pop:,} | {s['n']} | {s['positives']} | {_pct(s['rate'])} ({_pct(s['ci_low'])} to {_pct(s['ci_high'])}) |")
        if "estimated_missed" in e:
            m = e["estimated_missed"]
            out += ["", f"Estimated suspicious customer-months below the line: **{m['estimate']:.0f}** (95% interval {m['low']:.0f} to {m['high']:.0f})."]
        if btl.get("actual"):
            out += [f"Ground truth (available only in this synthetic setting): {btl['actual']['missed']} suspicious customer-months were in fact not alerted, "
                    f"{btl['actual']['of_near_miss']} of them in the near-miss stratum."]
        out += ["", "A high rate in the near-miss stratum means the thresholds are too tight for that rule; return to section 4."]
    out += ["", "## 7. Limitations and residual risk",
            "- Planted scenarios are stylised; real criminals adapt to thresholds, so tuned thresholds need periodic re-validation.",
            "- Look-alikes were designed to be separable by one parameter. Real false alerts are messier and tuning gains will be smaller.",
            "- Small numbers of scenarios per typology make recall coarse; holdout results with a handful of scenarios are indicative only.",
            "- Recall is measured per planted scenario, not per alert; one detected scenario can hide missed participants.",
            "- Thresholds were optimised rule by rule; interactions between rules are not modelled."]
    if warnings:
        out += ["", "### Warnings", ""] + [f"- {w}" for w in warnings]
    out += ["", "## 8. Approval", "",
            "| Role | Name | Decision | Date |", "|---|---|---|---|",
            "| Prepared by (compliance) | | | |", "| Model validation / second line | | | |", "| MLRO / approving officer | | | |", ""]
    return "\n".join(out)
